class HealthyPhiProvider:
    def __init__(self, parsed: dict | None = None) -> None:
        self.calls = 0
        self.parsed = parsed or {
            "business_goal": "Phi goal",
            "business_outcomes": ["Phi outcome"],
            "recommended_features": [{"title": "Phi Fault Monitoring", "description": "Generated by Phi."}],
        }

    def is_enabled(self) -> bool:
        return True

    def health_snapshot(self) -> dict:
        return {
            "deployment": "Phi-4",
            "health": "healthy",
            "last_success": "2026-06-20T00:00:00Z",
            "last_failure": None,
            "average_latency_ms": 1200,
            "consecutive_failures": 0,
        }

    def safe_config(self) -> dict:
        return {"configured": True, "deployment": "Phi-4", "deployment_health": "healthy"}

    def probe_json(self, *args, **kwargs) -> dict:
        self.calls += 1
        return {
            "status": "success",
            "http_status": 200,
            "elapsed_ms": 123,
            "raw_content": '{"ok":true}',
            "parsed_json": self.parsed,
        }


