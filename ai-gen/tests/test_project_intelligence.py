class HealthyPhiProvider:
    def __init__(self, parsed: dict | None = None) -> None:
        self.calls = 0
        self.parsed = parsed or {
            "business_goal": "Phi goal",
            "business_outcomes": ["Phi outcome"],
            "recommended_features": [{"title": "Phi Fault Monitoring", "description": "Generated by Phi."}],
        }

    def is_enabled(self) -> bool:
        return True

    def health_snapshot(self) -> dict:
        return {
            "deployment": "Phi-4",
            "health": "healthy",
            "last_success": "2026-06-20T00:00:00Z",
            "last_failure": None,
            "average_latency_ms": 1200,
            "consecutive_failures": 0,
        }

    def safe_config(self) -> dict:
        return {"configured": True, "deployment": "Phi-4", "deployment_health": "healthy"}

    def probe_json(self, *args, **kwargs) -> dict:
        self.calls += 1
        return {
            "status": "success",
            "http_status": 200,
            "elapsed_ms": 123,
            "raw_content": '{"ok":true}',
            "parsed_json": self.parsed,
        }


class FailingPhiProvider(HealthyPhiProvider):
    def probe_json(self, *args, **kwargs) -> dict:
        self.calls += 1
        return {
            "status": "timeout",
            "http_status": None,
            "elapsed_ms": 20000,
            "raw_content": "",
            "parsed_json": {},
            "failure_reason": "provider_timeout",
            "failure_message": "Azure Phi request timed out.",
            "parse_error": "TimeoutError",
        }


class RecordingPhiProvider(HealthyPhiProvider):
    def __init__(self, parsed: dict | None = None) -> None:
        super().__init__(parsed)
        self.system_prompt = ""
        self.user_prompt = ""

    def probe_json(self, system_prompt: str, user_prompt: str, **kwargs) -> dict:
        self.system_prompt = system_prompt
        self.user_prompt = user_prompt
        return super().probe_json(system_prompt, user_prompt, **kwargs)


class SequencePhiProvider(RecordingPhiProvider):
    def __init__(self, responses: list[dict]) -> None:
        super().__init__()
        self.responses = responses

    def probe_json(self, system_prompt: str, user_prompt: str, **kwargs) -> dict:
        self.calls += 1
        self.system_prompt = system_prompt
        self.user_prompt = user_prompt
        index = min(self.calls - 1, len(self.responses) - 1)
        return self.responses[index]


